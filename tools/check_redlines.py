#!/usr/bin/env python3
"""Reject commercial coupling, internal infrastructure, credentials, and local account data."""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

MARKERS = (
    "content-rater", "_SAU_ROOT", "CR_LICENSE", "publish_readback", "publish_metrics",
    "creator_accounts", "matrix", "风控冷却", "登录态桥接复活", ".18.do", ".2rd.cn",
    "192.168.", "/home/yangyan/", "/Users/", "BEGIN PRIVATE KEY", "BEGIN OPENSSH PRIVATE KEY",
)
SECRET = re.compile(r"(?:sk-[A-Za-z0-9]{20,}|AKIA[A-Z0-9]{16}|gho_[A-Za-z0-9]{20,})")
SUFFIXES = {".py", ".md", ".txt", ".toml", ".json", ".sh", ".yml", ".yaml"}


def check(root: Path) -> list[str]:
    issues: list[str] = []
    for path in sorted(root.rglob("*")):
        if not path.is_file() or ".git" in path.parts:
            continue
        relative = path.relative_to(root).as_posix()
        if "__pycache__" in path.parts or path.suffix in {".pyc", ".pyo"}:
            issues.append(f"{relative}: generated bytecode is forbidden in release content")
            continue
        if path.suffix not in SUFFIXES:
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        marker_exempt = path.name in {
            "check_redlines.py",
            "check_fill_only.py",
            "svcgate.py",
            "test_svcgate.py",
        }
        for marker in MARKERS:
            if marker in text and not marker_exempt:
                issues.append(f"{relative}: forbidden internal/commercial marker {marker!r}")
        if SECRET.search(text):
            issues.append(f"{relative}: possible embedded credential")
        if "matrix" in text.lower() and not marker_exempt:
            issues.append(f"{relative}: commercial matrix marker")
    return issues


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path)
    args = parser.parse_args()
    root = (args.root or Path(__file__).resolve().parents[1]).resolve()
    issues = check(root)
    if issues:
        print("\n".join(f"FAIL {issue}" for issue in issues), file=sys.stderr)
        return 1
    print("PASS no commercial dependencies, internal infrastructure, or embedded credentials")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
