from __future__ import annotations

import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from support import ROOT


class GateMutationTests(unittest.TestCase):
    def run_tool(self, name: str, root: Path, *extra: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, "-I", str(ROOT / "tools" / name), "--root", str(root), *extra],
            text=True, capture_output=True, timeout=20, check=False,
        )

    def test_dependency_pin_gate_fails_on_range(self) -> None:
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            (root / "requirements.txt").write_text("playwright>=1.0\n", encoding="utf-8")
            completed = self.run_tool("check_pins.py", root)
            self.assertNotEqual(completed.returncode, 0)
            self.assertIn("exact", completed.stderr)

    def test_redline_gate_fails_on_internal_infrastructure(self) -> None:
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            (root / "README.md").write_text("private host 192." + "168.0.1\n", encoding="utf-8")
            completed = self.run_tool("check_redlines.py", root)
            self.assertNotEqual(completed.returncode, 0)
            self.assertIn("forbidden", completed.stderr)

    def test_redline_gate_fails_on_generated_bytecode(self) -> None:
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            cache = root / "scripts" / "__pycache__"
            cache.mkdir(parents=True)
            (cache / "adapter.cpython-314.pyc").write_bytes(b"bytecode")
            completed = self.run_tool("check_redlines.py", root)
            self.assertNotEqual(completed.returncode, 0)
            self.assertIn("generated bytecode", completed.stderr)

    @unittest.skipUnless((ROOT / "src" / "fillup_core").is_dir(), "workspace-only vendoring check")
    def test_vendored_core_gate_fails_on_drift(self) -> None:
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            source = root / "src" / "fillup_core"
            source.mkdir(parents=True)
            (source / "one.py").write_text("VALUE = 1\n", encoding="utf-8")
            for skill in ("douyin-fill", "kuaishou-fill"):
                target = root / "skills" / skill / "scripts" / "fillup_core"
                target.mkdir(parents=True)
                (target / "one.py").write_text("VALUE = 1\n", encoding="utf-8")
            self.assertEqual(self.run_tool("vendor_core.py", root, "--check").returncode, 0)
            drift = root / "skills" / "douyin-fill" / "scripts" / "fillup_core" / "one.py"
            drift.write_text("VALUE = 2\n", encoding="utf-8")
            completed = self.run_tool("vendor_core.py", root, "--check")
            self.assertNotEqual(completed.returncode, 0)
            self.assertIn("differs", completed.stderr)


if __name__ == "__main__":
    unittest.main()
